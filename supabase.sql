-- BASE DE DATOS PARA INVITACIÓN DIGITAL DE GRADUACIÓN
-- Ejecuta este script en Supabase > SQL Editor.

create table if not exists public.graduation_rsvps (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 100),
  phone text,
  guests integer not null check (guests between 1 and 6),
  menu text not null check (menu in ('Pollo con tajadas','Carne asada','Pasta','Vegetariano')),
  notes text check (notes is null or char_length(notes) <= 300),
  confirmed boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.graduation_rsvps enable row level security;

-- Permite que la invitación pública registre confirmaciones.
drop policy if exists "Public can submit RSVP" on public.graduation_rsvps;
create policy "Public can submit RSVP"
on public.graduation_rsvps
for insert
to anon, authenticated
with check (
  confirmed = true
  and guests between 1 and 6
  and menu in ('Pollo con tajadas','Carne asada','Pasta','Vegetariano')
);

-- SOLO usuarios autenticados pueden consultar registros.
-- Para mayor seguridad, se recomienda limitar los usuarios administradores
-- mediante una política basada en una tabla de administradores.
drop policy if exists "Authenticated admins can read RSVP" on public.graduation_rsvps;
create policy "Authenticated admins can read RSVP"
on public.graduation_rsvps
for select
to authenticated
using (true);

grant insert on public.graduation_rsvps to anon, authenticated;
grant select on public.graduation_rsvps to authenticated;
